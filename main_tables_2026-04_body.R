# Helper: pull (beta, se) for given dep_var across distances 0..5 ----------
get_es <- function(DF, dep, samp, distances = 0:5){
  DF |>
    filter(sample == samp,
           dep_var == dep,
           interaction_group == "none",
           is.na(description)) |>
    select(distance, beta, std_error) |>
    distinct() |>
    complete(distance = distances) |>
    arrange(distance) |>
    filter(distance %in% distances)
}

