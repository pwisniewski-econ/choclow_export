# Format coef + tval for the destination/origin/control rows
fmt_coef <- function(b, p) sprintf("%10.4g%s", b, star(p))
fmt_tval <- function(t)   sprintf("(%5.2f)", t)

# Build columns
build_col <- function(spec, weighted_flag = FALSE){
  d_row <- get_cell(spec$dep_var, spec$controls, spec$naf2_fe, "destinationTRUE", weighted_flag)
  o_row <- get_cell(spec$dep_var, spec$controls, spec$naf2_fe, "originTRUE", weighted_flag)

  if (spec$controls){
    apl_row <- get_cell(spec$dep_var, spec$controls, spec$naf2_fe, "ln_apl_mean_0215", weighted_flag)
    emp_row <- get_cell(spec$dep_var, spec$controls, spec$naf2_fe, "ln_emp_mean_0215", weighted_flag)
  } else {
    apl_row <- tibble(beta = NA, tval = NA, pval = NA)
    emp_row <- tibble(beta = NA, tval = NA, pval = NA)
  }

  # P-value of equality test origin == destination, conservative (independent SE)
  z_val <- (o_row$beta - d_row$beta) / sqrt(o_row$std_error^2 + d_row$std_error^2)
  p_eq  <- 2 * (1 - pnorm(abs(z_val)))

  list(
    dest_b   = fmt_coef(d_row$beta, d_row$pval),
    dest_t   = fmt_tval(d_row$tval),
    orig_b   = fmt_coef(o_row$beta, o_row$pval),
    orig_t   = fmt_tval(o_row$tval),
    apl_b    = if (is.na(apl_row$beta)) "" else fmt_coef(apl_row$beta, apl_row$pval),
    apl_t    = if (is.na(apl_row$tval)) "" else fmt_tval(apl_row$tval),
    emp_b    = if (is.na(emp_row$beta)) "" else fmt_coef(emp_row$beta, emp_row$pval),
    emp_t    = if (is.na(emp_row$tval)) "" else fmt_tval(emp_row$tval),
    n_obs    = d_row$n_obs,
    r2       = d_row$r2,
    sec_fe   = if (spec$naf2_fe) "$\\surd $" else "",
    p_eq     = sprintf("%.3f", p_eq)
  )
}

# Pad function: estout uses width-aligned cells. We'll pad to 12 chars right-aligned for numbers.
pad <- function(x, w = 12){
  s <- as.character(x)
  if (nchar(s) < w) paste0(strrep(" ", w - nchar(s)), s) else s
}
cell <- function(x, full_w = 21){
  s <- as.character(x)
  if (nchar(s) >= full_w) s else paste0(s, strrep(" ", full_w - nchar(s)))
}

build_row <- function(values, leader, full_w = 21){
  vals <- map_chr(values, \(v) cell(v, full_w))
  paste0(cell(leader, 20), "&", paste(vals, collapse = "&"), "\\\\")
}

write_tbl2 <- function(weighted_flag, out_filename, regression_label, specs_use = specs){
  cols <- map(seq_len(nrow(specs_use)), \(i) build_col(specs_use[i, ], weighted_flag = weighted_flag))

  header1 <- paste0(strrep(" ", 20), "&",
    paste(map_chr(seq_len(nrow(specs_use)), \(i) cell(sprintf("\\multicolumn{1}{c}{(%d)}", i), 21)), collapse = "&"),
    "\\\\")
  header2 <- paste0(strrep(" ", 20), "&",
    paste(map_chr(seq_len(nrow(specs_use)), \(i) cell(sprintf("\\multicolumn{1}{c}{%s}", specs_use$label[i]), 21)), collapse = "&"),
    "\\\\")

  row_dest_b <- build_row(map_chr(cols, \(c) c$dest_b), "Destination firm")
  row_dest_t <- build_row(map_chr(cols, \(c) c$dest_t), "")
  row_orig_b <- build_row(map_chr(cols, \(c) c$orig_b), "Origin firm")
  row_orig_t <- build_row(map_chr(cols, \(c) c$orig_t), "")
  row_apl_b  <- build_row(map_chr(cols, \(c) c$apl_b),  "VA/worker")
  row_apl_t  <- build_row(map_chr(cols, \(c) c$apl_t),  "")
  row_emp_b  <- build_row(map_chr(cols, \(c) c$emp_b),  "Employees")
  row_emp_t  <- build_row(map_chr(cols, \(c) c$emp_t),  "")

  row_n      <- build_row(map_chr(cols, \(c) formatC(c$n_obs, format = "d")), "Observations")
  row_r2     <- build_row(map_chr(cols, \(c) sprintf("%.3f", c$r2)), "\\(R^{2}\\)")
  row_ar2    <- build_row(map_chr(cols, \(c) sprintf("%.3f", c$r2)), "Adjusted \\(R^{2}\\)")
  row_sec    <- build_row(map_chr(cols, \(c) c$sec_fe), "Sector FE")
  row_peq    <- build_row(map_chr(cols, \(c) c$p_eq), "P-value Origin-Destination")

  has_controls <- any(specs_use$controls)
  body <- if (has_controls) {
    c(row_dest_b, row_dest_t, "\\addlinespace",
      row_orig_b, row_orig_t, "\\addlinespace",
      row_apl_b,  row_apl_t,  "\\addlinespace",
      row_emp_b,  row_emp_t)
  } else {
    c(row_dest_b, row_dest_t, "\\addlinespace",
      row_orig_b, row_orig_t)
  }

  t3 <- c(
    paste0("% Generated by main_tables_2026-04_body.R from CASD CSV exports (Sortie 1)."),
    paste0("% tbl2-le5_panelsize0-fixed_all.csv (", regression_label, ")."),
    "% P-value of Origin-Destination equality is computed assuming independent SE",
    "% (conservative); CSV does not export the joint covariance.",
    "",
    header1, header2, "\\midrule",
    body,
    "\\midrule",
    row_n, row_r2, row_ar2, row_sec, row_peq
  )
  writeLines(t3, file.path(out_new, out_filename))
  cat("Wrote: ", file.path(out_new, out_filename), "\n", sep = "")
}

