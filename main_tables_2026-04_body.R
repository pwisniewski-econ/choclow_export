mean_cols <- c("fe0215_mlo_le", "ln_apl_mean_0215", "prod_res_mean_0215",
               "ln_lshare_mean_0215", "ln_emp_mean_0215")

agg_group <- function(rows){
  w    <- rows$n_siren
  out  <- vapply(mean_cols, \(v) weighted.mean(rows[[v]], w, na.rm = TRUE),
                 numeric(1))
  c(out, n_siren = sum(w))
}

means_pop  <- agg_group(MEANS[!MEANS$origin & !MEANS$destination, ])
means_org  <- agg_group(MEANS[ MEANS$origin                     , ])
means_dst  <- agg_group(MEANS[ MEANS$destination                , ])

format_n <- function(n) formatC(round(n), big.mark = ",", format = "d")
format_x <- function(x) sprintf("%.3f", x)
format_y <- function(x) formatC(round(x), big.mark = ",", format = "d")  # year

