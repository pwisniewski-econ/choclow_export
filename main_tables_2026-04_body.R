# Star helper (estout convention used in original tex: * 0.05, ** 0.01, *** 0.001)
star <- function(p){
  if (is.na(p)) return("")
  if (p < 0.001) "\\sym{***}"
  else if (p < 0.01) "\\sym{**}"
  else if (p < 0.05) "\\sym{*}"
  else ""
}

